import os
import json
import scipy
import datetime
import argparse
import numpy as np
from tqdm import tqdm
from wasabi import msg
from typing import List
from sentence_transformers import SentenceTransformer

# GLOBALS
GENERATION_ROOT_DIR = ""
EMBEDDER_NAME = "all-MiniLM-L6-v2"

def compute_distances_between_embeddings(embeddings_1: List[np.array],
                                         embeddings_2: List[np.array]) -> List[float]:
    """
    Computes the maximum cosine similarity for all points in embeddings_1 to each of the points in embeddings_2.
    :param embeddings_1:
    :type embeddings_1:
    :param embeddings_2:
    :type embeddings_2:
    :return:
    :rtype:
    """
    maximum_similarities = []
    for emb1 in embeddings_1:
        max_similarity = float('-inf')
        for emb2 in embeddings_2:
            similarity = 1 - scipy.spatial.distance.cosine(emb1, emb2)
            if similarity > max_similarity:
                max_similarity = similarity
        maximum_similarities.append(max_similarity)

    return maximum_similarities

def score_questions(input_file_path: str,
                    output_file_path: str,
                    embedder: SentenceTransformer):
    # Read the json file containing the examples
    with open(input_file_path, encoding="utf-8") as f:
        data = json.load(f)

    # Rephrase the questions
    print(f"Beginning similarity scoring of rephrased questions for {input_file_path}")
    for d in tqdm(data['data']):
        if 'rephrased_questions' in d:
            # Compute the embedding for each original question and rephrased question
            satyrn_question_embeddings = [embedder.encode(q) for q in d['questions']]
            rephrased_question_embeddings = [embedder.encode(q['question']) for q in d['rephrased_questions']]

            # Compute the maximum similarity from each of the rephrased questions with the original questions generated by Satyrn
            max_similarities = compute_distances_between_embeddings(rephrased_question_embeddings,
                                                                    satyrn_question_embeddings)

            # Store the max similarity for each of the questions
            for idx, rq in enumerate(d['rephrased_questions']):
                rq['similarity'] = max_similarities[idx]

    # Store the name of the embedding model that was used for computing the similarity score
    data['metadata']['similarity_score_model'] = EMBEDDER_NAME

    # Save the updated JSON dictionary with all the examples and the rephrased questions
    with open(output_file_path, "w", encoding="utf-8") as f:
        f.write(json.dumps(data, indent=4))

    msg.good(f"Finished similarity scoring for {input_file_path}")

def get_json_files(directory: str):
    # List all files in the directory
    files = os.listdir(directory)

    # Filter the list to include only .json files
    json_files = [f for f in files if f.endswith('.json')]

    return json_files

def main(benchmark_directory: str):

    INPUT_DIRS = {
        "train": os.path.join(benchmark_directory, "train"),
        "dev": os.path.join(benchmark_directory, "dev"),
        "test": os.path.join(benchmark_directory, "test")
    }

    # Load the embedding model
    EMBEDDER = SentenceTransformer(EMBEDDER_NAME)
    msg.good("Loaded the embedding model.")

    # Make the base directory to store all of the outputs
    ts = str(datetime.datetime.now()).replace(" ", "_")
    output_dir_name = f"scored_and_rephrased_dataset_{ts}"
    output_directory = os.path.join(GENERATION_ROOT_DIR, "generated_data", output_dir_name)
    os.mkdir(output_directory)

    # Determine the name of a new directory that will be generated the benchmark dataset
    OUTPUT_DIRS = {
        "train": os.path.join(output_directory, "train"),
        "dev": os.path.join(output_directory, "dev"),
        "test": os.path.join(output_directory, "test")
    }

    # Make sure the output directories exist
    for path in OUTPUT_DIRS.values():
        os.mkdir(path)

    train_files = get_json_files(INPUT_DIRS["train"])
    dev_files = get_json_files(INPUT_DIRS["dev"])
    test_files = get_json_files(INPUT_DIRS["test"])

    # Rephrase the train set questions
    for file_name in train_files:
        score_questions(os.path.join(INPUT_DIRS["train"], file_name), os.path.join(OUTPUT_DIRS["train"], file_name), EMBEDDER)

    # Rephrase the dev set questions
    for file_name in dev_files:
        score_questions(os.path.join(INPUT_DIRS["dev"], file_name), os.path.join(OUTPUT_DIRS["dev"], file_name), EMBEDDER)

    # Rephrase the test set questions
    for file_name in test_files:
        score_questions(os.path.join(INPUT_DIRS["test"], file_name), os.path.join(OUTPUT_DIRS["test"], file_name), EMBEDDER)

if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("benchmark_directory", type=str)
    args = parser.parse_args()
    main(args.benchmark_directory)
